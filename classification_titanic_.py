for epoch in range(0, epochs):

  tl_loss=0
  #model training
  for batch_train_features, batch_train_labels in train_loader:

    # forward propagation
    optimiser.zero_grad()
    y_pred_forward = model(batch_train_features)

    loss_value = loss_func(y_pred_forward,batch_train_labels.reshape(-1,1))


    loss_value.backward()
    optimiser.step()

    tl_loss += loss_value.item()*batch_train_features.size(0)

  tl_loss /= len(train_loader.dataset)

  # validation

  with torch.no_grad():
    vl_loss=0
    for batch_val_features, batch_val_labels in val_loader:
      # forward propagation

      y_val_pred = model(batch_val_features)

      loss_val = loss_func(y_val_pred, batch_val_labels.reshape(-1,1))

      vl_loss += loss_val.item()*batch_val_features.size(0)


  vl_loss /= len(val_loader.dataset)

  train_loss.append(tl_loss)
  val_loss.append(vl_loss)

  print("Epoch", epoch, "Train loss:", train_loss, "Val loss", val_loss)

