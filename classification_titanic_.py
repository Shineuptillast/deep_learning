class myDataset(Dataset):

  def __init__(self, features, labels):
    self.features = features
    self.labels = labels

  def __len__(self):
    return self.features.shape[0]

  def __getitem__(self, index):
    return self.features[index], self.labels[index]

train_dataset = myDataset(X_train_tensor, Y_train_tensor)
val_dataset = myDataset(X_val_tensor, Y_val_tensor)
test_dataset = myDataset(X_test_tensor, Y_test_tensor)

train_loader = DataLoader(train_dataset, batch_size=12, shuffle =True)
val_loader = DataLoader(val_dataset, batch_size=12, shuffle=True)
test_loader = DataLoader(test_dataset, batch_size=12, shuffle=True)

class mymodel(nn.Module):

  def __init__(self, features):
    super().__init__()

    self.network = nn.Sequential(
                      nn.Linear(features.shape[1], 16),
                      nn.ReLU(),
                      nn.Linear(16, 8),
                      nn.ReLU(),
                      nn.Linear(8,4),
                      nn.ReLU(),
                      nn.Linear(4,1),
                      nn.Sigmoid()
    )

  def forward(self, features):

    forward_output = self.network(features)

    return forward_output

model = mymodel(X_train_tensor)

