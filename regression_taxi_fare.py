class NNmodel(nn.Module):

  def __init__(self, features):
    super().__init__()
    self.features = features.shape[1]
    self.network = nn.Sequential(
        nn.Linear(self.features, 10),
        nn.Sigmoid(),
        nn.Linear(10, 5),
        nn.Sigmoid(),
        nn.Linear(5,1)

    )
  def forward(self, features):
    output = self.network(features)
    return output

