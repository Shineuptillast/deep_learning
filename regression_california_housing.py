import torch

class model():
  def __init__(self, features):
    self.weights = torch.rand(features.shape[1],1, dtype = torch.float32, requires_grad=True)
    self.bias = torch.zeros(1, dtype=torch.float32, requires_grad=True)

  def forward(self, features):
    z = torch.matmul(features, self.weights) + self.bias
    return z
  def loss_fn(self, y_true, y_pred):

    #mean squared error

    self.loss = (torch.sum(torch.pow((y_true-y_pred), 2))/len(y_pred))

    return self.loss

